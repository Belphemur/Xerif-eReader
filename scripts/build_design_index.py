#!/usr/bin/env python3
"""Generate docs/design/index.md from the design docs in that folder.

The design folder grew to 70+ records with no inventory. An agent starting
work on a subsystem has no cheap way to see which decisions still govern or
which drafts were superseded — the info exists only by reading every Status
line. This script lists the records and writes a markdown index so AGENTS.md
links one table instead of a maintained list.

    python3 scripts/build_design_index.py            # write docs/design/index.md
    python3 scripts/build_design_index.py --check    # exit 1 if stale (never writes)

`--check` compares content and never writes, so a gate is able to fail.

Xerif records are dated slugs (YYYY-MM-DD-topic.md), not numbered ADRs, so
there is no numbering to hand out: the date IS the identity and the sort key.
Prose docs (README.md) and the subdirectory history folders (reading-stats/,
ttf/) are skipped by the top-level matcher.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DESIGN_DIR = os.path.join(ROOT, "docs", "design")
OUT_PATH = os.path.join(DESIGN_DIR, "index.md")

# Top-level records only: README.md and the subdirectory folders (reading-stats/,
# ttf/) stay unindexed — they are history/prose, not decision records.
DOC_RE = re.compile(r"^\d{4}-\d{2}-\d{2}-.+\.md$")
TITLE_RE = re.compile(r"^#\s*(.+)$", re.M)
STATUS_RE = re.compile(r"status\s*:?\s*\**\s*([^\n*]+)", re.I)
# `SUPERSEDED by <file>` / `superseded — see <file>` in the doc head. Matches
# the file the supersession POINTS TO, so the index can render the link.
SUPERSEDED_BY_RE = re.compile(
    r"superseded[^\n]{0,120}?(?:by|see)\s+[`\[]?(\d{4}-\d{2}-\d{2}-[\w-]+\.md)", re.I)


def parse(path):
    with open(path) as f:
        text = f.read()
    head = text[:3000]
    m = TITLE_RE.search(head)
    title = m.group(1).strip() if m else os.path.basename(path)
    # Docs whose first heading is deeper than H1 (## Title) capture stray
    # hashes; strip them so the table shows the title, not the markup.
    title = re.sub(r"^#+\s*", "", title).strip()
    rel = os.path.basename(path)
    date = rel[:10]
    m = STATUS_RE.search(head)
    raw = m.group(1).strip().strip("*").strip() if m else ""
    return {
        "file": rel,
        "date": date,
        "title": title,
        "status": raw,
        "supersededBy": SUPERSEDED_BY_RE.search(head),
    }


def records():
    return [parse(os.path.join(DESIGN_DIR, f))
            for f in sorted(os.listdir(DESIGN_DIR)) if DOC_RE.match(f)]


def bucket_of(rec):
    """Bucket a record: live / draft / superseded.

    The discriminator is the PAST PARTICIPLE `superseded` (direction matters:
    a live record may SAY it supersedes another; `superseded by X` retires
    THIS one). Within non-superseded records, a Status starting with the
    draft words is a draft; everything else counts as live — 'implemented
    (PR #N)' and 'Accepted (as-built...)' both govern, and a doc that claims
    implementation stays live until something supersedes it.
    """
    s = rec["status"].lower()
    if "superseded" in s:
        return "superseded"
    if s.startswith(("draft", "proposed", "design approved", "probe round")):
        return "draft"
    return "live"


def build():
    recs = records()
    live, drafts, superseded = [], [], []
    for r in recs:
        {"live": live, "draft": drafts, "superseded": superseded}[bucket_of(r)].append(r)

    out = []
    w = out.append
    w("# Design record index")
    w("")
    w("Generated by `scripts/build_design_index.py` from the records in this")
    w("folder — **do not hand-edit**; edit the record, then run")
    w("`python3 scripts/build_design_index.py`. The repo-root `AGENTS.md` links")
    w("here and is not updated per record.")
    w("")
    w(f"**{len(recs)} top-level records.** One file per decision")
    w("(`YYYY-MM-DD-topic.md`); the date+slug is the identity — never renumber")
    w("or reuse one. A superseding decision is a NEW record that flips the old")
    w("one's Status to superseded; accepted records are never rewritten in")
    w("place. Draft records stay listed until they implement or are superseded.")
    w("")

    w("## In force")
    w("")
    w("Records that still govern. Skim the ones near your change before")
    w("proposing anything — they encode *why* the architecture is shaped the")
    w("way it is.")
    w("")
    w("| Record | Decision | Date |")
    w("| --- | --- | --- |")
    for r in live:
        w(f"| [{r['file']}]({r['file']}) | {r['title']} | {r['date']} |")
    w("")

    if drafts:
        w("## Draft / pending")
        w("")
        w("Records awaiting implementation or owner review. A draft is design")
        w("authority for its brief only until it implements — then flip the")
        w("Status to Accepted/implemented and it moves to In force on the next")
        w("regeneration.")
        w("")
        w("| Record | Decision | Status | Date |")
        w("| --- | --- | --- | --- |")
        for r in drafts:
            st = r["status"] or "no status line"
            w(f"| [{r['file']}]({r['file']}) | {r['title']} | {st} | {r['date']} |")
        w("")

    if superseded:
        w("## Not in force")
        w("")
        w("Superseded records — read these to understand why the current shape")
        w("is the shape.")
        w("")
        w("| Record | Decision | Superseded by | Date |")
        w("| --- | --- | --- | --- |")
        for r in superseded:
            m = r["supersededBy"]
            note = f"`{m.group(1)}`" if m else "—"
            w(f"| [{r['file']}]({r['file']}) | {r['title']} | {note} | {r['date']} |")
        w("")

    w("## Adding a record")
    w("")
    w("1. Name it `YYYY-MM-DD-topic.md` (the date is the identity and the")
    w("   index sort key).")
    w("2. Carry a Status line in the first 3000 chars so the index buckets it:")
    w("   `Status: Draft for owner review`, `Status: Accepted — implemented in")
    w("   PR #N`, `Status: SUPERSEDED by <file>`.")
    w("3. If it supersedes one, flip the old record's Status to SUPERSEDED by")
    w("   the new file in the same commit.")
    w("4. Regenerate the index and commit it in the same change.")
    w("5. Nothing else — `AGENTS.md` links here.")
    w("")
    return "\n".join(out)


def main():
    if "--check" in sys.argv:
        if not os.path.exists(OUT_PATH):
            print("check failed: index.md missing — run `python3 scripts/build_design_index.py`")
            return 1
        with open(OUT_PATH) as f:
            if f.read() != build():
                print("check failed: index.md is stale — run `python3 scripts/build_design_index.py`")
                return 1
        print("check ok: design index is current")
        return 0
    body = build()
    with open(OUT_PATH, "w") as f:
        f.write(body)
    print("wrote docs/design/index.md (%d records)" % len(records()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
