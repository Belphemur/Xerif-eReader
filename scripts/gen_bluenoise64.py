#!/usr/bin/env python3
"""Generate the TTF image engine's 64x64 blue-noise bake tables.

Emits src/activities/reader/BlueNoise64.cpp:

1. kBlueNoise64[64][64] — Ulichney's toroidal Void-and-Cluster blue-noise
   pattern (n=64, sigma=1.9, deterministic seed 1), tiled seamlessly at
   64-pixel boundaries so (x & 63, row & 63) never seams.
2. kBlueNoiseLinearLut[256] — the exact 512-byte linear-light quantizer:
   entry = (k << 9) | thresh, thresh = clamp(ceil(s), 0, 256) where
     v(g)   = 255 * (g/255)^2.2            (linear-light input, gamma 2.2)
     L_k    = 255 * (85k/255)^2.2          (the 4 panel levels in linear light)
     k      = the level interval v falls into (0..2)
     s      = (v - L_k) / (L_{k+1} - L_k) * 256
   For integer nz in [0,255]: s > nz  <=>  thresh > nz, so the runtime
   quantizer is `(entry >> 9) + (nz < (entry & 0x1FF))` — zero floats.

All math is IEEE-754 double, the same formula the host test
(LinearLutBitExactAgainstFloatReference) re-derives with C `pow` — the
runtime itself never computes a power. Run from the repo root:

    python3 scripts/gen_bluenoise64.py
"""
import os

import numpy as np

HEADER = """\
// GENERATED by scripts/gen_bluenoise64.py — do not edit by hand.
// Regenerate with: python3 scripts/gen_bluenoise64.py
//
// Design: docs/design/2026-11-08-ttf-image-contrast-and-fit.md (the
// linear-light blue-noise bake amendment). Both tables are 32-byte aligned
// (ESP32-S3 L1 data-cache line size): each 64-pixel row slice spans exactly
// two cache lines. Definitions live in this one translation unit so Flash
// .rodata holds a single copy.

#include "BlueNoise64.h"

"""


def void_and_cluster(n=64, sigma=1.9, seed=1):
    """Ulichney's toroidal void-and-cluster algorithm, deterministic."""
    rng = np.random.default_rng(seed)
    N = n * n
    ax = np.arange(n)
    ax = np.minimum(ax, n - ax)  # toroidal wraparound so 64x64 tiles seamlessly
    d2 = ax[:, None] ** 2 + ax[None, :] ** 2
    fk = np.fft.rfft2(np.exp(-d2 / (2.0 * sigma**2)))
    energy = lambda p: np.fft.irfft2(np.fft.rfft2(p.astype(np.float64)) * fk, s=(n, n))

    pat = np.zeros((n, n), dtype=bool)
    pat.flat[rng.choice(N, N // 10, replace=False)] = True
    for _ in range(4000):
        e = energy(pat)
        c = np.unravel_index(np.argmax(np.where(pat, e, -1e9)), (n, n))
        pat[c] = False
        e = energy(pat)
        v = np.unravel_index(np.argmin(np.where(~pat, e, 1e9)), (n, n))
        if v == c:
            pat[c] = True
            break
        pat[v] = True

    rank = np.zeros((n, n), dtype=np.int32)
    ones = int(pat.sum())
    p = pat.copy()
    for r in range(ones - 1, -1, -1):
        e = energy(p)
        c = np.unravel_index(np.argmax(np.where(p, e, -1e9)), (n, n))
        p[c] = False
        rank[c] = r
    p = pat.copy()
    for r in range(ones, N):
        e = energy(p)
        v = np.unravel_index(np.argmin(np.where(~p, e, 1e9)), (n, n))
        p[v] = True
        rank[v] = r
    return ((rank * 256) // N).astype(np.uint8)


def linear_lut():
    """The (k, thresh) entries, IEEE-754 double — see module docstring."""
    entries = []
    for g in range(256):
        v = 255.0 * (g / 255.0) ** 2.2
        levels = [255.0 * ((85 * k) / 255.0) ** 2.2 for k in range(4)]
        k = 0
        while k < 2 and v >= levels[k + 1]:
            k += 1
        s = (v - levels[k]) / (levels[k + 1] - levels[k]) * 256.0
        thresh = min(256, max(0, int(np.ceil(s))))
        entries.append((k, thresh))
    return entries


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "..", "src", "activities", "reader", "BlueNoise64.cpp")

    pattern = void_and_cluster()
    # Table invariants the tests pin too.
    assert sorted(pattern.flat) == sorted([v // 16 for v in range(4096)]), \
        "every rank value must appear exactly 16 times"
    lut = linear_lut()
    for g, (k, thresh) in enumerate(lut):
        if g in (0, 85, 170, 255):
            assert thresh == (256 if g == 255 else 0), f"palette anchor {g} must be solid"

    rows = []
    for y in range(64):
        rows.append("    " + ", ".join(f"{int(v):3d}" for v in pattern[y]) + ",")
    pattern_body = "\n".join(rows)

    lut_rows = []
    for i in range(0, 256, 8):
        vals = ", ".join(f"0x{(k << 9) | t:03x}" for k, t in lut[i : i + 8])
        lut_rows.append("    " + vals + ",")
    lut_body = "\n".join(lut_rows)

    with open(out, "w") as f:
        f.write(HEADER)
        f.write("namespace ttfimg {\n\n")
        f.write("alignas(32) extern const uint8_t kBlueNoise64[64][64] = {\n")
        f.write(pattern_body)
        f.write("\n};\n\n")
        f.write("// Entry layout: bits [10:9] = base level k (0..2), bits [8:0] = thresh\n"
                "// (0..256). Entry i quantizes source gray i in linear light; the anchors\n"
                "// {0, 85, 170, 255} are the solid levels {0, 1, 2, 3}.\n")
        f.write("alignas(32) extern const uint16_t kBlueNoiseLinearLut[256] = {\n")
        f.write(lut_body)
        f.write("\n};\n\n")
        f.write("}  // namespace ttfimg\n")
    print(f"wrote {os.path.normpath(out)}")


if __name__ == "__main__":
    main()
